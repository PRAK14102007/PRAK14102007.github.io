-- Only the owner account below can upload/delete. Everyone can view.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  year text not null,
  image text not null,
  storage_path text,
  desc text default '',
  wide boolean default false,
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
drop policy if exists "Anyone can view projects" on public.projects;
drop policy if exists "Owner can insert projects" on public.projects;
drop policy if exists "Owner can delete projects" on public.projects;
create policy "Anyone can view projects" on public.projects for select using (true);
create policy "Owner can insert projects" on public.projects for insert to authenticated with check ((auth.jwt() ->> 'email') = 'prakahrkuamrpandey933@gmail.com');
create policy "Owner can delete projects" on public.projects for delete to authenticated using ((auth.jwt() ->> 'email') = 'prakahrkuamrpandey933@gmail.com');

insert into storage.buckets (id, name, public)
values ('portfolio-images', 'portfolio-images', true)
on conflict (id) do update set public = true;

drop policy if exists "Public can view portfolio images" on storage.objects;
drop policy if exists "Owner can upload portfolio images" on storage.objects;
drop policy if exists "Owner can delete portfolio images" on storage.objects;
create policy "Public can view portfolio images" on storage.objects for select using (bucket_id = 'portfolio-images');
create policy "Owner can upload portfolio images" on storage.objects for insert to authenticated with check (bucket_id = 'portfolio-images' and (auth.jwt() ->> 'email') = 'prakahrkuamrpandey933@gmail.com' and (storage.foldername(name))[1] = (select auth.uid()::text));
create policy "Owner can delete portfolio images" on storage.objects for delete to authenticated using (bucket_id = 'portfolio-images' and (auth.jwt() ->> 'email') = 'prakahrkuamrpandey933@gmail.com' and (storage.foldername(name))[1] = (select auth.uid()::text));
